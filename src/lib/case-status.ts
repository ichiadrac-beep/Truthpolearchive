export function deskFromPath(path: string): DeskKey {
  if (path.includes("/ancient")) return "ancient";
  if (path.includes("/conspiracy")) return "conspiracy";
  return "archive";
}

export function statusOf(id: string, desk?: DeskKey): CaseStatus {
  if (CONFIRMED.has(id)) return "confirmed";
  if (DISPUTED.has(id)) return "disputed";
  if (UNRESOLVED.has(id)) return "unresolved";
  if (desk === "ancient") return "confirmed";
  if (desk === "conspiracy") return "disputed";
  return "unresolved";
}

export function statusLabel(id: string, desk?: DeskKey) {
  return CASE_STATUS_META[statusOf(id, desk)].label;
}
